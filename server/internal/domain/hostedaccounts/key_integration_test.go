func TestAccountKeysAreBoundToExplicitAccountsAndLiveIssuerAuthority(t *testing.T) {
	f := setup(t)
	parent := f.client(t, "Parent", f.user, hostedaccounts.AllCapabilities)
	child, err := f.svc.CreateChild(t.Context(), f.user, f.org, parent.AccountID, "Child", f.host, hostedaccounts.DefaultCapabilities)
	require.NoError(t, err)
	sibling := f.client(t, "Sibling", f.user, hostedaccounts.AllCapabilities)
	require.NoError(t, f.svc.SetAncestorGrant(t.Context(), f.host, f.org, child.AccountID, parent.AccountID, hostedaccounts.View|hostedaccounts.ManagePools|hostedaccounts.ChangePools))
	generic := apikey.NewService(sqlstores.NewSQLApiKeyStore(f.db), nil)
	keys := hostedaccounts.NewKeyService(f.svc, generic)
	issued, err := keys.Create(t.Context(), f.user, f.org, parent.AccountID, hostedaccounts.KeyOptions{Name: "Automation", Capabilities: hostedaccounts.View | hostedaccounts.ChangePools, DescendantAccountIDs: []string{child.AccountID}})
	require.NoError(t, err)
	record, err := generic.Validate(t.Context(), issued.Secret)
	require.NoError(t, err)
	_, orgUser := record.AsUser()
	require.False(t, orgUser, "an account credential must never authenticate as an organization credential")
	caps, err := keys.Authorize(t.Context(), record.ID, f.user, f.org, parent.AccountID)
	require.NoError(t, err)
	require.Equal(t, hostedaccounts.View|hostedaccounts.ChangePools, caps)
	caps, err = keys.Authorize(t.Context(), record.ID, f.user, f.org, child.AccountID)
	require.NoError(t, err)
	require.Equal(t, hostedaccounts.View|hostedaccounts.ChangePools, caps)
	_, err = keys.Authorize(t.Context(), record.ID, f.user, f.org, sibling.AccountID)
	require.Error(t, err, "another membership does not widen this key")
	require.NoError(t, f.svc.RevokeAncestorGrant(t.Context(), f.host, f.org, child.AccountID, parent.AccountID))
	_, err = keys.Authorize(t.Context(), record.ID, f.user, f.org, child.AccountID)
	require.Error(t, err, "a stored descendant bound is not an authorization grant")
	require.NoError(t, keys.Revoke(t.Context(), f.user, f.org, parent.AccountID, issued.Key.KeyID))
	_, err = generic.Validate(t.Context(), issued.Secret)
	require.Error(t, err)
	_, err = keys.Authorize(t.Context(), record.ID, f.user, f.org, parent.AccountID)
	require.Error(t, err, "execution rechecks also reject revoked credentials")
}

func TestFutureDescendantKeysRequireOptInAndPrivateAccess(t *testing.T) {
	f := setup(t)
	parent := f.client(t, "Parent", f.user, hostedaccounts.AllCapabilities)
	listed, err := f.svc.CreateChild(t.Context(), f.user, f.org, parent.AccountID, "Listed subclient", f.host, hostedaccounts.DefaultCapabilities)
	require.NoError(t, err)
	existing, err := f.svc.CreateChild(t.Context(), f.user, f.org, parent.AccountID, "Unlisted existing subclient", f.host, hostedaccounts.DefaultCapabilities)
	require.NoError(t, err)
	require.NoError(t, f.svc.SetAncestorGrant(t.Context(), f.host, f.org, listed.AccountID, parent.AccountID, hostedaccounts.View|hostedaccounts.ChangePools))
	credentials := apikey.NewService(sqlstores.NewSQLApiKeyStore(f.db), nil)
	keys := hostedaccounts.NewKeyService(f.svc, credentials)
	fixed, err := keys.Create(t.Context(), f.user, f.org, parent.AccountID, hostedaccounts.KeyOptions{Name: "Fixed", Capabilities: hostedaccounts.View | hostedaccounts.ChangePools, DescendantAccountIDs: []string{listed.AccountID}})
	require.NoError(t, err)
	automatic, err := keys.Create(t.Context(), f.user, f.org, parent.AccountID, hostedaccounts.KeyOptions{Name: "Future", Capabilities: hostedaccounts.View | hostedaccounts.ChangePools, DescendantAccountIDs: []string{listed.AccountID}, IncludeFutureDescendants: true})
	require.NoError(t, err)
	require.True(t, automatic.Key.IncludeFutureDescendants)
	require.Equal(t, []string{listed.AccountID}, automatic.Key.DescendantAccountIds)
	metadata, _, err := keys.List(t.Context(), f.user, f.org, parent.AccountID, 0, "")
	require.NoError(t, err)
	var listedAutomatic hostedaccounts.AccountKey
	for _, item := range metadata {
		if item.KeyID == automatic.Key.KeyID {
			listedAutomatic = item
		}
	}
	require.Equal(t, automatic.Key.KeyID, listedAutomatic.KeyID)
	require.True(t, listedAutomatic.IncludeFutureDescendants, "listing exposes the broader opt-in alongside the explicit selection")
	require.Equal(t, []string{listed.AccountID}, listedAutomatic.DescendantAccountIds)
	fixedRecord, err := credentials.Validate(t.Context(), fixed.Secret)
	require.NoError(t, err)
	automaticRecord, err := credentials.Validate(t.Context(), automatic.Secret)
	require.NoError(t, err)
	_, err = keys.Authorize(t.Context(), fixedRecord.ID, f.user, f.org, listed.AccountID)
	require.NoError(t, err, "fixed keys retain their explicitly selected descendants")
	_, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, existing.AccountID)
	require.Error(t, err, "the opt-in does not grant private access to an existing child")
	require.NoError(t, f.svc.SetAncestorGrant(t.Context(), f.host, f.org, existing.AccountID, parent.AccountID, hostedaccounts.View|hostedaccounts.ChangePools))
	_, err = keys.Authorize(t.Context(), fixedRecord.ID, f.user, f.org, existing.AccountID)
	require.Error(t, err, "unlisted existing descendants do not enter a fixed key's scope")
	caps, err := keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, existing.AccountID)
	require.NoError(t, err)
	require.Equal(t, hostedaccounts.View|hostedaccounts.ChangePools, caps, "the opt-in includes existing unlisted direct children")
	require.NoError(t, f.svc.RevokeAncestorGrant(t.Context(), f.host, f.org, existing.AccountID, parent.AccountID))
	_, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, existing.AccountID)
	require.Error(t, err, "live issuer access is still required after opting in")
	child, err := f.svc.CreateChild(t.Context(), f.user, f.org, parent.AccountID, "New subclient", f.host, hostedaccounts.DefaultCapabilities)
	require.NoError(t, err)
	_, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, child.AccountID)
	require.Error(t, err, "future opt-in is not private account access")
	require.NoError(t, f.svc.SetAncestorGrant(t.Context(), f.host, f.org, child.AccountID, parent.AccountID, hostedaccounts.View|hostedaccounts.ChangePools))
	_, err = keys.Authorize(t.Context(), fixedRecord.ID, f.user, f.org, child.AccountID)
	require.Error(t, err, "new descendants do not enter a fixed key's scope")
	caps, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, child.AccountID)
	require.NoError(t, err)
	require.Equal(t, hostedaccounts.View|hostedaccounts.ChangePools, caps)
	require.NoError(t, f.svc.ConfigureChild(t.Context(), f.host, f.org, parent.AccountID, hostedaccounts.View|hostedaccounts.ManageMembers|hostedaccounts.Delegate, false))
	caps, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, child.AccountID)
	require.NoError(t, err)
	require.Equal(t, hostedaccounts.View, caps, "live ceilings reduce a key's effective authority")
	require.NoError(t, f.svc.ConfigureChild(t.Context(), f.host, f.org, parent.AccountID, hostedaccounts.AllCapabilities, true))
	_, err = keys.Authorize(t.Context(), automaticRecord.ID, f.user, f.org, child.AccountID)
	require.Error(t, err, "suspension immediately blocks account credentials")
}

func TestAccountKeyLifecycleStaysPrivateAndCannotBecomeHostCredentials(t *testing.T) {
	f := setup(t)
	account := f.client(t, "Customer", f.host, hostedaccounts.DefaultCapabilities)
	require.NoError(t, f.svc.SetMembership(t.Context(), f.host, f.org, account.AccountID, f.user, hostedaccounts.RoleViewer))
	credentials := apikey.NewService(sqlstores.NewSQLApiKeyStore(f.db), nil)
	keys := hostedaccounts.NewKeyService(f.svc, credentials)
	own, err := keys.Create(t.Context(), f.user, f.org, account.AccountID, hostedaccounts.KeyOptions{Name: "Read", Capabilities: hostedaccounts.View})
	require.NoError(t, err)
	_, err = keys.Create(t.Context(), f.user, f.org, account.AccountID, hostedaccounts.KeyOptions{Name: "Too broad", Capabilities: hostedaccounts.View | hostedaccounts.ChangePools})
	require.Error(t, err, "a key cannot exceed its issuer's rights")
	other, err := keys.Create(t.Context(), f.host, f.org, account.AccountID, hostedaccounts.KeyOptions{Name: "Operator", Capabilities: hostedaccounts.MachineCapabilities})
	require.NoError(t, err)
	listed, _, err := keys.List(t.Context(), f.user, f.org, account.AccountID, 0, "")
	require.NoError(t, err)
	require.Len(t, listed, 1)
	require.Equal(t, own.Key.KeyID, listed[0].KeyID)
	require.Error(t, keys.Revoke(t.Context(), f.user, f.org, account.AccountID, other.Key.KeyID))
	listed, _, err = keys.List(t.Context(), f.host, f.org, account.AccountID, 0, "")
	require.NoError(t, err)
	require.Len(t, listed, 2)
	hostKeys, err := credentials.List(t.Context(), f.org)
	require.NoError(t, err)
	require.Empty(t, hostKeys)
	require.Error(t, credentials.Revoke(t.Context(), other.Key.KeyID, f.org, "host", "host"), "host key lifecycle must not revoke private account credentials")
	_, err = credentials.Validate(t.Context(), other.Secret)
	require.NoError(t, err)
	_, err = f.db.ExecContext(t.Context(), `DELETE FROM hosted_account WHERE id=$1`, account.ID)
	require.NoError(t, err)
	record, err := credentials.Validate(t.Context(), other.Secret)
	require.NoError(t, err)
	_, isHost := record.AsUser()
	require.False(t, isHost, "removing a scope must not downgrade its credential kind")
	_, err = keys.Authorize(t.Context(), record.ID, f.host, f.org, account.AccountID)
	require.Error(t, err)
}

func TestAccountKeyExpiryUsesExecutionTimeInsideAnOlderTransaction(t *testing.T) {
	f := setup(t)
	account := f.client(t, "Customer", f.host, hostedaccounts.DefaultCapabilities)
	credentials := apikey.NewService(sqlstores.NewSQLApiKeyStore(f.db), nil)
	keys := hostedaccounts.NewKeyService(f.svc, credentials)
	issued, err := keys.Create(t.Context(), f.host, f.org, account.AccountID, hostedaccounts.KeyOptions{Name: "Expiring", Capabilities: hostedaccounts.View})
	require.NoError(t, err)
	record, err := credentials.Validate(t.Context(), issued.Secret)
	require.NoError(t, err)
	tx, err := f.db.BeginTx(t.Context(), nil)
	require.NoError(t, err)
	defer tx.Rollback()
	_, err = tx.ExecContext(t.Context(), `SELECT pg_sleep(0.01)`)
	require.NoError(t, err)
	_, err = tx.ExecContext(t.Context(), `UPDATE api_key SET expires_at=clock_timestamp() WHERE id=$1`, record.ID)
	require.NoError(t, err)
	_, err = keys.Authorize(db.WithTxQueries(t.Context(), sqlc.New(tx)), record.ID, f.host, f.org, account.AccountID)
	require.Error(t, err, "an expired key must fail even when the transaction started before expiry")
}
